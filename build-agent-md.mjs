// Copies the agent view of index.html (the page as plain Markdown) to llms.txt and README.md;
// README.md leaves out the News section.
// Run after editing the agent view:  node build-agent-md.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const read = (file) => readFileSync(new URL(file, import.meta.url), 'utf8');
const write = (file, text) => writeFileSync(new URL(file, import.meta.url), text);

const view = read('index.html').match(/<div class="agent-view__md">([\s\S]*?)<\/div>/);
if (!view) throw new Error('index.html: agent view not found');
if (/<[a-z/]/i.test(view[1])) throw new Error('index.html: the agent view must hold only Markdown text');
const unescape = (s) => s.replace(/&(amp|lt|gt|quot|#39);/g, (_, e) => ({ amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'" })[e]);

const markdown = `${unescape(view[1])}\n`;
const readme = markdown.replace(/^## News\n[\s\S]*?(?=^## )/m, '');
write('llms.txt', markdown);
write('README.md', `<!-- Generated by build-agent-md.mjs from the agent view in index.html: edit that and rerun it. -->\n\n${readme}`);
console.log(`llms.txt: ${markdown.split('\n').length} lines, README.md: ${readme.split('\n').length} lines`);
